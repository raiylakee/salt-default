auto
to_lower (std::string s) -> std::string
{
  std::transform (s.begin (), s.end (), s.begin (),
                  [] (unsigned char c) { return std::tolower (c); });
  return s;
}

auto
trim (std::string s) -> std::string
{
  const auto not_space = [] (unsigned char c) { return !std::isspace (c); };
  s.erase (s.begin (), std::find_if (s.begin (), s.end (), not_space));
  s.erase (std::find_if (s.rbegin (), s.rend (), not_space).base (), s.end ());
  return s;
}

auto
split_colon (const std::string &s) -> std::vector<std::string>
{
  std::vector<std::string> out;
  std::string cur;
  std::istringstream ss (s);
  while (std::getline (ss, cur, ':'))
    {
      cur = trim (cur);
      if (!cur.empty ())
        {
          out.push_back (cur);
        }
    }
  return out;
}

// XDG MIME Applications spec.
constexpr const char *kGroupDefaults = "Default Applications";
constexpr const char *kGroupAdded = "Added Associations";
constexpr const char *kGroupRemoved = "Removed Associations";

constexpr const char *kGroupDesktop = "Desktop Entry";

// Generated by update-desktop-database: GIO's system-default candidate list.
constexpr const char *kGroupMimeCache = "MIME Cache";

// XDG_CURRENT_DESKTOP as a set, for OnlyShowIn/NotShowIn.
auto
current_desktops () -> std::vector<std::string>
{
  const char *env = std::getenv ("XDG_CURRENT_DESKTOP");
  return split_colon (env != nullptr ? env : "");
}

// Mirror what Gio::AppInfo::should_show() applies to GIO's own entries.
auto
desktop_shows_in_current (const Glib::RefPtr<Glib::KeyFile> &kf) -> bool
{
  const auto current = current_desktops ();
  const auto listed = [&current] (const std::string &name)
    {
      return std::find (current.begin (), current.end (), name)
             != current.end ();
    };

  try
    {
      if (kf->has_key (kGroupDesktop, "OnlyShowIn"))
        {
          const auto only = kf->get_string_list (kGroupDesktop, "OnlyShowIn");
          bool found = false;
          for (const auto &name : only)
            {
              found = found || listed (name);
            }
          if (!only.empty () && !found)
            {
              return false;
            }
        }
    }
  catch (const Glib::Error &)
    {
    }

  try
    {
      if (kf->has_key (kGroupDesktop, "NotShowIn"))
        {
          for (const auto &name :
               kf->get_string_list (kGroupDesktop, "NotShowIn"))
            {
              if (listed (name))
                {
                  return false;
                }
            }
        }
    }
  catch (const Glib::Error &)
    {
    }

  return true;
}

// A missing or malformed boolean must not abort the whole scan.
auto
desktop_bool (const Glib::RefPtr<Glib::KeyFile> &kf, const char *key) -> bool
{
  try
    {
      return kf->has_key (kGroupDesktop, key)
             && kf->get_boolean (kGroupDesktop, key);
    }
  catch (const Glib::Error &)
    {
      return false;
    }
}

void
ensure_parent_dir (const std::string &file)
{
  std::error_code ec;
  fs::path p (file);
  if (p.has_parent_path ())
    {
      fs::create_directories (p.parent_path (), ec);
    }
}

// KEEP_COMMENTS keeps the user's comments when the file is written back.
auto
load_keyfile (const std::string &path) -> Glib::RefPtr<Glib::KeyFile>
{
  auto kf = Glib::KeyFile::create ();
  try
    {
      kf->load_from_file (path, Glib::KeyFile::Flags::KEEP_COMMENTS);
    }
  catch (const Glib::Error &)
    {
      // Missing or unreadable file: callers treat this as "no user config".
    }
  return kf;
}

// The Flatpak wrapper names the sandbox's mount of the host root.
constexpr const char *kHostRootEnv = "SALT_HOST_ROOT";

// Icon= is a themed name or an absolute path (Desktop Entry spec). A name
// resolves to what Gio::AppInfo builds for the same value; an absolute path is
// also tried under the host root, which is where a sandbox keeps the file a
// host desktop file names.
auto
icon_from_value (const std::string &value) -> Glib::RefPtr<Gio::Icon>
{
  if (value.empty ())
    {
      return {};
    }
  if (value[0] != '/')
    {
      try
        {
          return Gio::ThemedIcon::create (value);
        }
      catch (...)
        {
          return {};
        }
    }

  std::vector<std::string> candidates{ value };
  const char *root = std::getenv (kHostRootEnv);
  if (root != nullptr && *root != '\0')
    {
      candidates.emplace_back (std::string (root) + value);
    }

  for (const auto &path : candidates)
    {
      // The renderer walks the filesystem, so only point at a file that is
      // really there.
      if (Glib::file_test (path, Glib::FileTest::EXISTS))
        {
          return Glib::wrap (G_FILE_ICON (
              g_file_icon_new (Gio::File::create_for_path (path)->gobj ())));
        }
      spdlog::debug ("icon {} not found", path);
    }
  return {};
}

