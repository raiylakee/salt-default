MimeService::MimeService () = default;

auto
MimeService::is_scheme_mime (const std::string &mime) -> bool
{
  constexpr std::string_view prefix = "x-scheme-handler/";
  return mime.rfind (prefix.data (), 0) == 0;
}

auto
MimeService::scheme_name (const std::string &mime) -> std::string
{
  constexpr std::string_view prefix = "x-scheme-handler/";
  if (is_scheme_mime (mime))
    {
      return mime.substr (prefix.size ());
    }
  return mime;
}

auto
MimeService::xdg_data_home () -> std::string
{
  if (const char *env = std::getenv ("XDG_DATA_HOME");
      env != nullptr && *env != '\0')
    {
      return env;
    }
  const char *home = std::getenv ("HOME");
  if (home == nullptr || *home == '\0')
    {
      return "/usr/share";
    }
  return fs::path (home) / ".local" / "share";
}

auto
MimeService::xdg_data_dirs () -> std::vector<std::string>
{
  // Flatpak exports come through these env vars (XDG Base Directory spec).
  std::vector<std::string> dirs;
  dirs.push_back (xdg_data_home ());

  const char *env = std::getenv ("XDG_DATA_DIRS");
  std::string raw
      = (env != nullptr && *env != '\0') ? env : "/usr/local/share:/usr/share";
  for (auto &d : split_colon (raw))
    {
      if (std::find (dirs.begin (), dirs.end (), d) == dirs.end ())
        {
          dirs.push_back (d);
        }
    }
  return dirs;
}

auto
MimeService::user_config_path () -> std::string
{
  const char *xdg = std::getenv ("XDG_CONFIG_HOME");
  fs::path base;
  if (xdg != nullptr && *xdg != '\0')
    {
      base = xdg;
    }
  else
    {
      const char *home = std::getenv ("HOME");
      base = fs::path (home != nullptr ? home : "/") / ".config";
    }
  return base / "mimeapps.list";
}

auto
MimeService::try_exec_available (const std::string &try_exec) -> bool
{
  std::string prog = trim (try_exec);
  if (prog.empty ())
    {
      return true;
    }
  // TryExec may carry arguments; only the binary matters.
  auto sp = prog.find (' ');
  if (sp != std::string::npos)
    {
      prog = prog.substr (0, sp);
    }
  if (prog.find ('/') != std::string::npos)
    {
      return ::access (prog.c_str (), X_OK) == 0;
    }
  const char *path_env = std::getenv ("PATH");
  std::string path_raw = path_env != nullptr ? path_env : "/usr/bin:/bin";
  std::string cur;
  std::istringstream ss (path_raw);
  while (std::getline (ss, cur, ':'))
    {
      if (cur.empty ())
        {
          continue;
        }
      if (::access ((fs::path (cur) / prog).c_str (), X_OK) == 0)
        {
          return true;
        }
    }
  return false;
}

void
MimeService::ensure_globs_loaded ()
{
  if (globs_loaded_)
    {
      return;
    }
  globs_loaded_ = true;

  for (auto &dir : xdg_data_dirs ())
    {
      fs::path globs = fs::path (dir) / "mime" / "globs";
      std::ifstream file (globs);
      if (!file.is_open ())
        {
          continue;
        }
      std::string line;
      while (std::getline (file, line))
        {
          if (line.empty () || line[0] == '#')
            {
              continue;
            }
          auto sep = line.find (':');
          if (sep == std::string::npos)
            {
              continue;
            }
          std::string mime = line.substr (0, sep);
          std::string pattern = line.substr (sep + 1);
          if (!pattern.empty () && pattern[0] == '*')
            {
              auto &vec = globs_[mime];
              if (std::find (vec.begin (), vec.end (), pattern) == vec.end ())
                {
                  if (vec.size () < 4)
                    {
                      vec.push_back (pattern);
                    }
                }
            }
        }
    }
}

auto
MimeService::describe (const std::string &mime) -> std::string
{
  if (is_scheme_mime (mime))
    {
      return scheme_name (mime) + " link";
    }
  try
    {
      Glib::ustring desc = Gio::content_type_get_description (mime);
      if (!desc.empty ())
        {
          return desc;
        }
    }
  catch (const Glib::Error &e)
    {
      spdlog::debug ("no description for {}: {}", mime, e.what ());
    }
  return mime;
}

auto
MimeService::extensions_for (const std::string &mime) -> std::string
{
  if (is_scheme_mime (mime))
    {
      return scheme_name (mime) + ":";
    }
  ensure_globs_loaded ();
  auto it = globs_.find (mime);
  if (it == globs_.end () || it->second.empty ())
    {
      return mime;
    }
  std::string out;
  for (size_t i = 0; i < it->second.size (); ++i)
    {
      if (i > 0)
        {
          out += ", ";
        }
      out += it->second[i];
    }
  return out;
}

auto
MimeService::load_apps () -> std::vector<AppEntry>
{
  std::vector<AppEntry> apps;
  auto all = Gio::AppInfo::get_all ();
  for (auto &info : all)
    {
      if (!info)
        {
          continue;
        }
      bool show = true;
      try
        {
          show = info->should_show ();
        }
      catch (...)
        {
          show = true;
        }
      if (!show)
        {
          continue;
        }
      // Hidden= and a missing TryExec binary must not appear either;
      // should_show() covers only NoDisplay/OnlyShowIn/NotShowIn.
      auto desktop = std::dynamic_pointer_cast<Gio::DesktopAppInfo> (info);
      if (desktop)
        {
          try
            {
              if (desktop->is_hidden ())
                {
                  continue;
                }
            }
          catch (...)
            {
            }
          try
            {
              if (desktop->has_key ("TryExec")
                  && !try_exec_available (
                      std::string (desktop->get_string ("TryExec"))))
                {
                  spdlog::debug ("hiding {}: TryExec missing",
                                 info->get_id ());
                  continue;
                }
            }
          catch (...)
            {
            }
        }
      AppEntry e = entry_from_app_info (info);
      if (e.id.empty ())
        {
          continue;
        }
      if (e.name.empty ())
        {
          e.name = e.id;
        }
      apps.push_back (std::move (e));
    }

  // Desktop files GIO refused, which inside a sandbox is every host
  // application. They are still valid choices for the host.
  synthetic_ids_.clear ();
  for (auto &entry : synthetic_apps ())
    {
      synthetic_ids_.insert (entry.id);
      apps.push_back (std::move (entry));
    }
  synthetic_ids_loaded_ = true;

  std::sort (
      apps.begin (), apps.end (), [] (const AppEntry &a, const AppEntry &b)
        { return to_lower (a.name.raw ()) < to_lower (b.name.raw ()); });
  return apps;
}

auto
MimeService::entry_from_app_info (const Glib::RefPtr<Gio::AppInfo> &info)
    -> AppEntry
{
  AppEntry e;
  e.gapp = info;
  try
    {
      e.id = info->get_id ();
    }
  catch (...)
    {
      return e;
    }
  try
    {
      e.name = info->get_name ();
    }
  catch (...)
    {
      e.name = e.id;
    }
  try
    {
      e.description = info->get_description ();
    }
  catch (...)
    {
    }
  // Read Icon= from the desktop file: GIO returns a file icon for an absolute
  // path, and that path is a host path when the app info comes from outside.
  try
    {
      if (auto desktop = std::dynamic_pointer_cast<Gio::DesktopAppInfo> (info))
        {
          if (desktop->has_key ("Icon"))
            {
              e.icon = icon_from_value (desktop->get_string ("Icon"));
            }
        }
    }
  catch (...)
    {
    }
  if (!e.icon)
    {
      try
        {
          e.icon = info->get_icon ();
        }
      catch (...)
        {
        }
    }
  try
    {
      for (auto &t : info->get_supported_types ())
        {
          e.supported_types.emplace_back (t);
        }
    }
  catch (...)
    {
    }

  if (auto desktop = std::dynamic_pointer_cast<Gio::DesktopAppInfo> (info))
    {
      try
        {
          if (desktop->has_key ("TryExec"))
            {
              e.try_exec = desktop->get_string ("TryExec");
            }
          e.terminal = desktop->has_key ("Terminal")
                           ? desktop->get_boolean ("Terminal")
                           : false;
          e.desktop_file = desktop->get_filename ();
        }
      catch (...)
        {
        }
    }
  return e;
}

auto
MimeService::scan_skipped_desktop_files (
    const std::set<std::string> &known_ids) -> std::vector<AppEntry>
{
  std::vector<AppEntry> out;
  std::set<std::string> seen = known_ids;

  for (const auto &dir : xdg_data_dirs ())
    {
      const fs::path apps_dir = fs::path (dir) / "applications";
      std::error_code ec;
      if (!fs::is_directory (apps_dir, ec))
        {
          continue;
        }

      for (fs::recursive_directory_iterator it (apps_dir, ec), end;
           !ec && it != end; it.increment (ec))
        {
          std::error_code entry_ec;
          if (!it->is_regular_file (entry_ec))
            {
              continue;
            }
          const fs::path path = it->path ();
          if (path.extension () != ".desktop")
            {
              continue;
            }

          // Desktop file ID: path relative to applications/, '/' → '-'.
          std::string id = fs::relative (path, apps_dir, ec).generic_string ();
          if (ec)
            {
              continue;
            }
          std::replace (id.begin (), id.end (), '/', '-');
          if (!seen.insert (id).second)
            {
              continue; // earlier data directories win
            }

          auto kf = Glib::KeyFile::create ();
          try
            {
              kf->load_from_file (path.string ());
            }
          catch (const Glib::Error &)
            {
              continue; // unreadable or not a desktop entry
            }
          if (!kf->has_group (kGroupDesktop) || desktop_bool (kf, "Hidden")
              || desktop_bool (kf, "NoDisplay")
              || !desktop_shows_in_current (kf))
            {
              continue;
            }
          // GIO only turns Type=Application entries into app infos.
          try
            {
              if (kf->get_string (kGroupDesktop, "Type") != "Application")
                {
                  continue;
                }
            }
          catch (const Glib::Error &)
            {
              continue;
            }

          Glib::ustring name;
          try
            {
              name = kf->get_locale_string (kGroupDesktop, "Name");
            }
          catch (const Glib::Error &)
            {
            }
          if (name.empty ())
            {
              continue;
            }

          AppEntry e;
          e.id = id;
          e.name = name;
          e.desktop_file = path.string ();
          e.synthetic = true;
          e.terminal = desktop_bool (kf, "Terminal");
          try
            {
              e.description = kf->get_locale_string (kGroupDesktop, "Comment");
            }
          catch (const Glib::Error &)
            {
            }
          try
            {
              if (kf->has_key (kGroupDesktop, "TryExec"))
                {
                  e.try_exec = kf->get_string (kGroupDesktop, "TryExec");
                }
            }
          catch (const Glib::Error &)
            {
            }

          try
            {
              if (kf->has_key (kGroupDesktop, "Icon"))
                {
                  e.icon = icon_from_value (
                      kf->get_locale_string (kGroupDesktop, "Icon"));
                }
            }
          catch (const Glib::Error &)
            {
            }
          try
            {
              for (auto &t : kf->get_string_list (kGroupDesktop, "MimeType"))
                {
                  if (!t.empty ())
                    {
                      e.supported_types.emplace_back (t);
                    }
                }
            }
          catch (const Glib::Error &)
            {
            }

          spdlog::debug ("listing {}: its Exec/TryExec is not resolvable here",
                         e.id);
          out.push_back (std::move (e));
        }
    }
  return out;
}

auto
MimeService::synthetic_apps () -> std::vector<AppEntry>
{
  // Outside a sandbox GIO is authoritative: an unresolvable Exec/TryExec
  // really does mean the entry cannot be launched, so it stays hidden.
  if (std::getenv ("FLATPAK_ID") == nullptr)
    {
      return {};
    }

  std::set<std::string> known;
  for (auto &info : Gio::AppInfo::get_all ())
    {
      if (!info)
        {
          continue;
        }
      try
        {
          known.insert (info->get_id ());
        }
      catch (...)
        {
        }
    }
  return scan_skipped_desktop_files (known);
}

void
MimeService::ensure_synthetic_ids_loaded ()
{
  if (synthetic_ids_loaded_)
    {
      return;
    }
  synthetic_ids_.clear ();
  for (auto &entry : synthetic_apps ())
    {
      synthetic_ids_.insert (entry.id);
    }
  synthetic_ids_loaded_ = true;
}

void
MimeService::ensure_mimeinfo_loaded ()
{
  if (mimeinfo_loaded_)
    {
      return;
    }
  mimeinfo_loaded_ = true;
  mimeinfo_.clear ();

  // XDG precedence: the first data directory listing a type wins.
  for (const auto &dir : xdg_data_dirs ())
    {
      auto kf = load_keyfile (
          (fs::path (dir) / "applications" / "mimeinfo.cache").string ());
      if (!kf->has_group (kGroupMimeCache))
        {
          continue;
        }
      for (const auto &key : kf->get_keys (kGroupMimeCache))
        {
          if (mimeinfo_.count (key) != 0)
            {
              continue;
            }
          try
            {
              std::vector<std::string> ids;
              for (const auto &id : kf->get_string_list (kGroupMimeCache, key))
                {
                  if (!id.empty ())
                    {
                      ids.emplace_back (id);
                    }
                }
              if (!ids.empty ())
                {
                  mimeinfo_[key] = std::move (ids);
                }
            }
          catch (const Glib::Error &e)
            {
              spdlog::debug ("bad mimeinfo.cache entry {}: {}", key,
                             e.what ());
            }
        }
    }
}

auto
MimeService::system_default_id (const std::string &mime) -> std::string
{
  ensure_mimeinfo_loaded ();
  ensure_mimeapps_loaded ();

  auto it = mimeinfo_.find (mime);
  if (it == mimeinfo_.end ())
    {
      return {};
    }

  // The system default is the first candidate that survives removals.
  auto removed = removed_associations_.find (mime);
  for (const auto &id : it->second)
    {
      if (removed != removed_associations_.end ()
          && std::find (removed->second.begin (), removed->second.end (), id)
                 != removed->second.end ())
        {
          continue;
        }
      return id;
    }
  return {};
}

auto
MimeService::load_file_types () -> std::vector<MimeTypeEntry>
{
  std::vector<std::string> mimes;
  try
    {
      auto registered = Gio::content_types_get_registered ();
      for (auto &t : registered)
        {
          Glib::ustring mt = Gio::content_type_get_mime_type (t);
          std::string mime = mt.empty () ? std::string (t) : std::string (mt);
          if (!is_scheme_mime (mime))
            {
              mimes.push_back (mime);
            }
        }
    }
  catch (const Glib::Error &e)
    {
      spdlog::warn ("content_types_get_registered failed: {}", e.what ());
    }

  // Always include types claimed by apps even if not in the
  // XDG mime database (e.g. custom types).
  for (auto &app : Gio::AppInfo::get_all ())
    {
      if (!app)
        {
          continue;
        }
      try
        {
          for (auto &t : app->get_supported_types ())
            {
              std::string mime (t);
              if (!is_scheme_mime (mime)
                  && std::find (mimes.begin (), mimes.end (), mime)
                         == mimes.end ())
                {
                  mimes.push_back (mime);
                }
            }
        }
      catch (...)
        {
        }
    }

  std::sort (mimes.begin (), mimes.end ());
  mimes.erase (std::unique (mimes.begin (), mimes.end ()), mimes.end ());

  std::vector<MimeTypeEntry> out;
  out.reserve (mimes.size ());
  for (auto &m : mimes)
    {
      MimeTypeEntry e;
      e.mime = m;
      e.is_scheme = false;
      e.description = describe (m);
      e.extensions_label = extensions_for (m);
      out.push_back (std::move (e));
    }
  return out;
}

auto
MimeService::load_schemes () -> std::vector<MimeTypeEntry>
{
  std::vector<std::string> mimes;
  for (auto &app : Gio::AppInfo::get_all ())
    {
      if (!app)
        {
          continue;
        }
      try
        {
          for (auto &t : app->get_supported_types ())
            {
              std::string mime (t);
              if (is_scheme_mime (mime)
                  && std::find (mimes.begin (), mimes.end (), mime)
                         == mimes.end ())
                {
                  mimes.push_back (mime);
                }
            }
        }
      catch (...)
        {
        }
    }
  // Include well-known schemes even when no app claims them so the
  // user can still assign one (mirrors Windows link-type list).
  for (const char *known : { "x-scheme-handler/http", "x-scheme-handler/https",
                             "x-scheme-handler/mailto", "x-scheme-handler/ftp",
                             "x-scheme-handler/file" })
    {
      if (std::find (mimes.begin (), mimes.end (), known) == mimes.end ())
        {
          mimes.emplace_back (known);
        }
    }

  std::sort (mimes.begin (), mimes.end ());
  std::vector<MimeTypeEntry> out;
  for (auto &m : mimes)
    {
      MimeTypeEntry e;
      e.mime = m;
      e.is_scheme = true;
      e.scheme = scheme_name (m);
      e.description = describe (m);
      e.extensions_label = extensions_for (m);
      out.push_back (std::move (e));
    }
  return out;
}

auto
MimeService::default_for (const std::string &mime)
    -> Glib::RefPtr<Gio::AppInfo>
{
  try
    {
      return Gio::AppInfo::get_default_for_type (mime, false);
    }
  catch (const Glib::Error &e)
    {
      spdlog::debug ("get_default_for_type({}) failed: {}", mime, e.what ());
      return {};
    }
}

auto
MimeService::apps_for (const std::string &mime)
    -> std::vector<Glib::RefPtr<Gio::AppInfo>>
{
  try
    {
      return Gio::AppInfo::get_all_for_type (mime);
    }
  catch (const Glib::Error &e)
    {
      spdlog::debug ("get_all_for_type({}) failed: {}", mime, e.what ());
      return {};
    }
}

auto
MimeService::apps_for_chooser (const std::string &mime)
    -> std::vector<AppEntry>
{
  std::vector<AppEntry> out;
  std::set<std::string> seen;

  for (auto &info : apps_for (mime))
    {
      if (!info)
        {
          continue;
        }
      AppEntry e = entry_from_app_info (info);
      if (e.id.empty () || !seen.insert (e.id).second)
        {
          continue;
        }
      out.push_back (std::move (e));
    }

  // Synthetic entries: offer them when their desktop file declares the type
  // or when they are the recorded default, so a choice stays visible.
  const std::string current = user_default_id (mime);
  for (auto &e : synthetic_apps ())
    {
      if (seen.count (e.id))
        {
          continue;
        }
      const bool declares = std::find (e.supported_types.begin (),
                                       e.supported_types.end (), mime)
                            != e.supported_types.end ();
      if (!declares && e.id != current)
        {
          continue;
        }
      seen.insert (e.id);
      out.push_back (std::move (e));
    }
  return out;
}

auto
MimeService::set_default (const Glib::RefPtr<Gio::AppInfo> &app,
                          const std::string &mime, std::string &error_out)
    -> bool
{
  if (!app)
    {
      error_out = "no application selected";
      return false;
    }
  try
    {
      bool ok = app->set_as_default_for_type (mime);
      if (!ok)
        {
          error_out = "backend reported failure";
          return false;
        }
      invalidate_mimeapps_cache ();
      return true;
    }
  catch (const Glib::Error &e)
    {
      error_out = e.what ();
      spdlog::error ("set_as_default_for_type({}) failed: {}", mime,
                     error_out);
      return false;
    }
}

auto
MimeService::set_default (const AppEntry &app, const std::string &mime,
                          std::string &error_out) -> bool
{
  if (app.gapp)
    {
      return set_default (app.gapp, mime, error_out);
    }
  if (app.id.empty ())
    {
      error_out = "no application selected";
      return false;
    }
  if (!write_user_default (app.id, mime, error_out))
    {
      return false;
    }
  invalidate_mimeapps_cache ();
  return true;
}

auto
MimeService::write_user_default (const std::string &desktop_id,
                                 const std::string &mime,
                                 std::string &error_out) -> bool
{
  try
    {
      const std::string path = user_config_path ();
      auto kf = load_keyfile (path);

      // Choosing an application implies allowing it for the type.
      kf->set_string (kGroupDefaults, mime, desktop_id);

      std::vector<Glib::ustring> added;
      if (kf->has_group (kGroupAdded) && kf->has_key (kGroupAdded, mime))
        {
          added = kf->get_string_list (kGroupAdded, mime);
        }
      if (std::find (added.begin (), added.end (), Glib::ustring (desktop_id))
          == added.end ())
        {
          added.emplace_back (desktop_id);
        }
      kf->set_string_list (kGroupAdded, mime, added);

      if (kf->has_group (kGroupRemoved) && kf->has_key (kGroupRemoved, mime))
        {
          auto removed = kf->get_string_list (kGroupRemoved, mime);
          removed.erase (std::remove (removed.begin (), removed.end (),
                                      Glib::ustring (desktop_id)),
                         removed.end ());
          if (removed.empty ())
            {
              kf->remove_key (kGroupRemoved, mime);
              if (kf->has_group (kGroupRemoved)
                  && kf->get_keys (kGroupRemoved).empty ())
                {
                  kf->remove_group (kGroupRemoved);
                }
            }
          else
            {
              kf->set_string_list (kGroupRemoved, mime, removed);
            }
        }

      ensure_parent_dir (path);
      if (!kf->save_to_file (path))
        {
          error_out = "could not write " + path;
          return false;
        }
      return true;
    }
  catch (const Glib::Error &e)
    {
      error_out = e.what ();
      spdlog::error ("write_user_default({}, {}) failed: {}", mime, desktop_id,
                     error_out);
      return false;
    }
}

auto
MimeService::reset_to_system (const std::string &mime, std::string &error_out)
    -> bool
{
  try
    {
      // Removes the user override so the system default applies again.
      Gio::AppInfo::reset_type_associations (mime);
      invalidate_mimeapps_cache ();
      return true;
    }
  catch (const Glib::Error &e)
    {
      error_out = e.what ();
      spdlog::error ("reset_type_associations({}) failed: {}", mime,
                     error_out);
      return false;
    }
  catch (const std::exception &e)
    {
      error_out = e.what ();
      return false;
    }
}

void
MimeService::ensure_mimeapps_loaded ()
{
  if (mimeapps_loaded_)
    {
      return;
    }
  mimeapps_loaded_ = true;
  user_defaults_.clear ();
  removed_associations_.clear ();

  auto kf = load_keyfile (user_config_path ());

  if (kf->has_group (kGroupDefaults))
    {
      for (const auto &key : kf->get_keys (kGroupDefaults))
        {
          try
            {
              auto list = kf->get_string_list (kGroupDefaults, key);
              if (!list.empty () && !list.front ().empty ())
                {
                  user_defaults_[key] = list.front ();
                }
            }
          catch (const Glib::Error &e)
            {
              spdlog::debug ("bad mimeapps default entry {}: {}", key,
                             e.what ());
            }
        }
    }

  if (kf->has_group (kGroupRemoved))
    {
      for (const auto &key : kf->get_keys (kGroupRemoved))
        {
          try
            {
              auto list = kf->get_string_list (kGroupRemoved, key);
              std::vector<std::string> ids;
              for (const auto &id : list)
                {
                  if (!id.empty ())
                    {
                      ids.emplace_back (id);
                    }
                }
              if (!ids.empty ())
                {
                  removed_associations_[key] = std::move (ids);
                }
            }
          catch (const Glib::Error &e)
            {
              spdlog::debug ("bad mimeapps removed entry {}: {}", key,
                             e.what ());
            }
        }
    }
}

void
MimeService::invalidate_mimeapps_cache ()
{
  mimeapps_loaded_ = false;
  user_defaults_.clear ();
  removed_associations_.clear ();
}

auto
MimeService::is_user_default (const std::string &mime) -> bool
{
  ensure_mimeapps_loaded ();
  return user_defaults_.find (mime) != user_defaults_.end ();
}

auto
MimeService::default_source (const std::string &mime) -> std::string
{
  ensure_mimeapps_loaded ();
  if (user_defaults_.find (mime) != user_defaults_.end ())
    {
      return "user";
    }
  if (default_for (mime))
    {
      return "system";
    }
  // GIO skipping every candidate is not conclusive inside a sandbox: the one
  // it had to skip can still be the default the host uses.
  const std::string system = system_default_id (mime);
  if (!system.empty () && synthetic_ids_.count (system) != 0)
    {
      return "system";
    }
  return "none";
}

auto
MimeService::user_default_id (const std::string &mime) -> std::string
{
  ensure_mimeapps_loaded ();
  auto it = user_defaults_.find (mime);
  return it == user_defaults_.end () ? std::string () : it->second;
}

auto
MimeService::default_app_id (const std::string &mime) -> std::string
{
  ensure_synthetic_ids_loaded ();

  const std::string user = user_default_id (mime);
  if (!user.empty () && synthetic_ids_.count (user) != 0)
    {
      // A host application this sandbox cannot build, so GIO skipped it.
      return user;
    }

  std::string gio;
  if (auto def = default_for (mime))
    {
      try
        {
          gio = def->get_id ();
        }
      catch (...)
        {
        }
    }

  if (!user.empty ())
    {
      // gio is empty only when nothing was buildable; the id still names the
      // application the host would pick.
      return gio.empty () ? user : gio;
    }

  if (!gio.empty ())
    {
      // GIO may have answered with a fallthrough; mimeinfo.cache knows better.
      const std::string system = system_default_id (mime);
      if (!system.empty () && synthetic_ids_.count (system) != 0
          && system != gio)
        {
          return system;
        }
      return gio;
    }

  // Nothing was buildable: mimeinfo.cache names the host's default.
  const std::string system = system_default_id (mime);
  return synthetic_ids_.count (system) != 0 ? system : std::string ();
}

auto
MimeService::removed_associations_for (const std::string &mime)
    -> std::vector<std::string>
{
  ensure_mimeapps_loaded ();
  auto it = removed_associations_.find (mime);
  if (it == removed_associations_.end ())
    {
      return {};
    }
  return it->second;
}

auto
MimeService::is_association_removed (const std::string &app_id,
                                     const std::string &mime) -> bool
{
  auto ids = removed_associations_for (mime);
  return std::find (ids.begin (), ids.end (), app_id) != ids.end ();
}

auto
MimeService::remove_association (const std::string &app_id,
                                 const std::string &mime,
                                 std::string &error_out) -> bool
{
  try
    {
      const std::string path = user_config_path ();
      auto kf = load_keyfile (path);

      std::vector<Glib::ustring> list;
      if (kf->has_group (kGroupRemoved) && kf->has_key (kGroupRemoved, mime))
        {
          list = kf->get_string_list (kGroupRemoved, mime);
        }
      if (std::find (list.begin (), list.end (), Glib::ustring (app_id))
          == list.end ())
        {
          list.emplace_back (app_id);
        }
      kf->set_string_list (kGroupRemoved, mime, list);

      ensure_parent_dir (path);
      if (!kf->save_to_file (path))
        {
          error_out = "could not write " + path;
          return false;
        }
      invalidate_mimeapps_cache ();
      return true;
    }
  catch (const Glib::Error &e)
    {
      error_out = e.what ();
      spdlog::error ("remove_association({}, {}) failed: {}", mime, app_id,
                     error_out);
      return false;
    }
}

auto
MimeService::restore_association (const std::string &app_id,
                                  const std::string &mime,
                                  std::string &error_out) -> bool
{
  try
    {
      const std::string path = user_config_path ();
      auto kf = load_keyfile (path);
      if (!kf->has_group (kGroupRemoved) || !kf->has_key (kGroupRemoved, mime))
        {
          return true; // nothing removed, already allowed
        }

      auto list = kf->get_string_list (kGroupRemoved, mime);
      list.erase (
          std::remove (list.begin (), list.end (), Glib::ustring (app_id)),
          list.end ());
      if (list.empty ())
        {
          kf->remove_key (kGroupRemoved, mime);
          if (kf->get_keys (kGroupRemoved).empty ())
            {
              kf->remove_group (kGroupRemoved);
            }
        }
      else
        {
          kf->set_string_list (kGroupRemoved, mime, list);
        }

      ensure_parent_dir (path);
      if (!kf->save_to_file (path))
        {
          error_out = "could not write " + path;
          return false;
        }
      invalidate_mimeapps_cache ();
      return true;
    }
  catch (const Glib::Error &e)
    {
      error_out = e.what ();
      spdlog::error ("restore_association({}, {}) failed: {}", mime, app_id,
                     error_out);
      return false;
    }
}

